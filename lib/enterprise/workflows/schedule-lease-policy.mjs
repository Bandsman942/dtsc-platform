import { createHash, timingSafeEqual } from "node:crypto";

/**
 * WF-06S2E2 (#855): PURE, INERT receipt lease *plans*, NEVER an authority to
 * claim, renew, execute, settle, retry an ERP effect, or mutate any row.
 *
 * No route, cron, worker or business action imports this file. #852 must bind
 * every future transition to an authorized, tenant-scoped DB transaction with
 * CAS + live actor/source/entitlement checks, and atomically emit run/outbox.
 * In particular, a plan built from untrusted arguments is NOT permission.
 */
export const INERT_WORKFLOW_LEASE_POLICY = Object.freeze({
  maxAttempts: 3,       // Must track WORKFLOW_LIMITS.maxAttempts in constants.ts
  leaseSeconds: 90,     // Must track WORKFLOW_LIMITS.workerLeaseSeconds
  maxCatchUpMs: 24 * 60 * 60 * 1000,
});

function denied(code) {
  // Deliberately do not include tenant IDs, tokens, payloads or any input.
  throw new Error("WORKFLOW_INERT_LEASE_" + code);
}
function nonempty(value) {
  return typeof value === "string" && value.length > 0
    && value.length <= 191 && value.trim() === value;
}
function validInstant(value) {
  return value instanceof Date && Number.isFinite(value.getTime());
}
function validNow(asOf) {
  if (!validInstant(asOf)) denied("CLOCK_INVALID");
}
function validRevision(value) {
  return Number.isSafeInteger(value) && value > 0;
}
function noEffects(receipt) {
  return receipt.workflowRunId == null && receipt.outboxEventId == null
    && receipt.completedAt == null && receipt.lastFailureCode == null;
}

/** Identical local wall-clock (including DST fall-back) => identical receipt. */
export function canonicalInertWorkflowOccurrenceKey(receipt) {
  if (!receipt || typeof receipt !== "object"
    || !nonempty(receipt.organizationId) || !nonempty(receipt.scheduleId)
    || !nonempty(receipt.workflowVersionId)
    || typeof receipt.localDate !== "string"
    || !/^\d{4}-\d{2}-\d{2}$/.test(receipt.localDate)
    || typeof receipt.localTime !== "string"
    || !/^([01]\d|2[0-3]):[0-5]\d$/.test(receipt.localTime)) {
    denied("IDENTITY_INVALID");
  }
  const [y, m, d] = receipt.localDate.split("-").map(Number);
  const epoch = Date.UTC(y, m - 1, d);
  const normalized = new Date(epoch);
  // Validate local calendar components only; never derive a business date
  // from a UTC ISO string (ERP #670 date contract).
  if (!Number.isFinite(epoch)
    || normalized.getUTCFullYear() !== y
    || normalized.getUTCMonth() + 1 !== m
    || normalized.getUTCDate() !== d) {
    denied("LOCAL_DATE_INVALID");
  }
  return createHash("sha256").update(JSON.stringify([
    receipt.organizationId, receipt.scheduleId, receipt.workflowVersionId,
    receipt.localDate, receipt.localTime,
  ])).digest("hex");
}

/**
 * This is a conservative suggestion, NOT a claim and NOT a permission.
 * It requires an unmodified RESERVED receipt with the deterministic identity
 * generated by advanced-schedule.ts. It NEVER returns a SQL update payload.
 */
export function planInertWorkflowScheduleClaim(receipt, asOf) {
  validNow(asOf);
  if (!receipt || typeof receipt !== "object" || !nonempty(receipt.id)) {
    denied("RECEIPT_INVALID");
  }
  const canonical = canonicalInertWorkflowOccurrenceKey(receipt);
  if (receipt.occurrenceKey !== canonical) denied("KEY_MISMATCH");
  if (receipt.status !== "RESERVED") denied("STATUS_INVALID");
  if (!validRevision(receipt.revision)) denied("REVISION_INVALID");
  if (receipt.attemptCount !== 0 || receipt.claimToken != null
    || receipt.leaseUntil != null || receipt.claimedAt != null
    || !noEffects(receipt)) denied("ALREADY_MUTATED");
  if (!validInstant(receipt.scheduledAt)) denied("DUE_INVALID");
  const delay = asOf.getTime() - receipt.scheduledAt.getTime();
  if (delay < 0) denied("NOT_DUE");
  if (delay > INERT_WORKFLOW_LEASE_POLICY.maxCatchUpMs) denied("CATCHUP_EXCEEDED");
  if (receipt.revision === Number.MAX_SAFE_INTEGER) denied("REVISION_EXHAUSTED");

  return Object.freeze({
    kind: "INERT_LEASE_PLAN_ONLY",
    receiptId: receipt.id,
    organizationId: receipt.organizationId,
    occurrenceKey: canonical,
    expectedStatus: "RESERVED",
    expectedRevision: receipt.revision,
    hypotheticalNextRevision: receipt.revision + 1,
    hypotheticalFirstAttempt: 1,
    hypotheticalLeaseSeconds: INERT_WORKFLOW_LEASE_POLICY.leaseSeconds,
    authorized: false,
    executable: false,
  });
}

/**
 * Fence validation on a hypothetical CLAIMED snapshot.
 * Schema #850 blocks CLAIMED in production today. This function cannot
 * authorize a new attempt or replay a financial action.
 *
 * Token is compared in constant time after hashing; never returned/logged.
 */
export function assessInertWorkflowLeaseFence(receipt, offeredToken, asOf) {
  validNow(asOf);
  if (!receipt || typeof receipt !== "object" || receipt.status !== "CLAIMED") {
    denied("NOT_CLAIMED");
  }
  const canonical = canonicalInertWorkflowOccurrenceKey(receipt);
  if (receipt.occurrenceKey !== canonical) denied("KEY_MISMATCH");
  if (!nonempty(receipt.id) || !validRevision(receipt.revision)) denied("RECEIPT_INVALID");
  if (!Number.isSafeInteger(receipt.attemptCount)
    || receipt.attemptCount < 1
    || receipt.attemptCount > INERT_WORKFLOW_LEASE_POLICY.maxAttempts) {
    denied("ATTEMPTS_INVALID");
  }
  if (!noEffects(receipt)) denied("EFFECT_ALREADY_LINKED");
  if (!validInstant(receipt.leaseUntil) || !validInstant(receipt.claimedAt)
    || receipt.leaseUntil.getTime() <= asOf.getTime()
    || receipt.claimedAt.getTime() > asOf.getTime()
    || receipt.leaseUntil.getTime() <= receipt.claimedAt.getTime()
    || receipt.leaseUntil.getTime() - receipt.claimedAt.getTime()
       > INERT_WORKFLOW_LEASE_POLICY.leaseSeconds * 1000) {
    denied("LEASE_INVALID");
  }
  if (typeof offeredToken !== "string" || offeredToken.length < 16
    || offeredToken.length > 191
    || typeof receipt.claimToken !== "string"
    || receipt.claimToken.length < 16 || receipt.claimToken.length > 191) {
    denied("TOKEN_INVALID");
  }
  const given = createHash("sha256").update(offeredToken).digest();
  const stored = createHash("sha256").update(receipt.claimToken).digest();
  if (!timingSafeEqual(given, stored)) denied("TOKEN_MISMATCH");

  return Object.freeze({
    kind: "INERT_LEASE_FENCE_ONLY",
    receiptId: receipt.id,
    organizationId: receipt.organizationId,
    occurrenceKey: canonical,
    expectedStatus: "CLAIMED",
    expectedRevision: receipt.revision,
    observedAttempt: receipt.attemptCount,
    authorized: false,
    executable: false,
  });
}
