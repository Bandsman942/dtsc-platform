import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = file=>readFileSync(new URL("../"+file,import.meta.url),"utf8");
const billing=read("lib/health-billing.ts");
const invoiceRoute=read("app/api/enterprise/[organizationId]/healthcare/medical-billing/[invoiceId]/route.ts");
const regression=read("scripts/qa-regression-checks.mjs");
const slice=billing.slice(billing.indexOf("export async function billingAction"));
assert.match(slice,/pg_advisory_xact_lock/,"All invoice actions require transaction lock");
assert.match(slice,/organizationId.*health-medical-invoice.*invoiceId/,"Lock must be tenant and invoice scoped");
assert.match(slice,/new Prisma\.Decimal\(data\.amount\)/,"Payment precision cannot use JS Number");
assert.match(slice,/new Prisma\.Decimal\(invoice\.balanceAmount\)/,"Remaining balance must use Prisma Decimal");
assert.match(slice,/money\(balance\.minus\(amount\)\)/,"Subtraction must retain decimal precision");
assert.match(slice,/amount\.lte\(0\)/,"Zero/negative payment rejected");
assert.match(slice,/PAYMENT_EXCEEDS_BALANCE/,"Overpayment blocked");
assert.match(slice,/paymentReference,status:"CONFIRMED"/,"Active duplicate references must be rejected");
assert.match(slice,/PAYMENT_REFERENCE_ALREADY_USED/,"Duplicate references must not charge twice");
assert.match(slice,/nextBalance\.isZero\(\)/,"Final payment must close invoice exactly");
assert.match(slice,/PAYMENT_REVERSAL_INVALID/,"Payment reversal cannot produce negative paid amount");
assert.doesNotMatch(slice,/const amount=Number\(data\.amount\)/,"Binary float must not calculate payments");
assert.match(invoiceRoute,/consultation:access\.canViewSensitive\?true:false/,"Invoice detail must not expose clinical consultation by default");
assert.match(invoiceRoute,/labRequest:access\.canViewSensitive\?true:false/,"Invoice detail must not expose laboratory results by default");
assert.match(invoiceRoute,/PAYMENT_REFERENCE_ALREADY_USED/,"API must explain duplicate reference");
assert.match(regression,/qa-health-05-payments\.mjs/);
console.log("✅ HEALTH-05 P0: invoice lock, Decimal balance, duplicate reference guard and clinical projection minimization");
